/******************************************************
 * schaltet led nach bitmuster an

*******************************************************/
uint8_t countdown(uint8_t number, uint8_t *reset)
{
    static uint32_t countdown_timer = 0;
    static int8_t n;
    char buffer[4];

    if(*reset)
    {
    	countdown_timer=0;
    	n=number;
    	*reset=0;
    }

    // Piep nach kurzer Zeit wieder ausschalten
    if(HAL_GetTick() >= countdown_timer - 850)
    {
    	buzzer_set_frequency(0);
    	 if(n<0)
    	    	return 1;
    }

    if(HAL_GetTick() >= countdown_timer)
    {
        countdown_timer = HAL_GetTick() +1000;
        SSD1306_Clear();

        // Zahl anzeigen
        sprintf(buffer, "%d", n);

        if(n >= 10)
            SSD1306_GotoXY(48, 20);
        else
            SSD1306_GotoXY(56, 20);
        SSD1306_Puts(buffer, &Font_16x26, SSD1306_COLOR_WHITE);

        SSD1306_UpdateScreen();

        buzzer_set_frequency(2000);

        n--;
    }
    return 0;
}


/******************************************************
 * schaltet led nach bitmuster an

*******************************************************/
uint8_t ShowText(oled_screen_t *liste, uint8_t list_size, uint8_t *reset)
{

	static uint32_t screen_timer=0;
	static uint8_t i=0, j=0;

	if(*reset)
	{
		i=0;
		j=0;
		*reset=0;
	}


	if(HAL_GetTick()>= screen_timer)
	{
		if(i>=list_size)
			return 1;

		SSD1306_Clear();

		for(j=0; j<3; j++)
		{
			if(liste[i].line[j].text==NULL)
				break;

			SSD1306_GotoXY(liste[i].line[j].pos.x, liste[i].line[j].pos.y);
			SSD1306_Puts(liste[i].line[j].text, liste[i].line[j].Font, SSD1306_COLOR_WHITE);
		}
		SSD1306_UpdateScreen();

		screen_timer=HAL_GetTick()+liste[i].delay;

		i++;
	}

	return 0;
}



/******************************************************
 * schaltet led nach bitmuster an

*******************************************************/
void ShowTime(RTC_TimeTypeDef sTime)
{
	static uint32_t timer=0;
	char timeString[9];

	if(HAL_GetTick()>=timer)
	{
		timer=HAL_GetTick()+1000;
		sprintf(timeString, "%02d:%02d:%02d", sTime.Hours, sTime.Minutes, sTime.Seconds);
		SSD1306_GotoXY(20, 20);
		SSD1306_Clear();
		SSD1306_Puts(timeString, &Font_11x18, SSD1306_COLOR_WHITE);
		SSD1306_UpdateScreen();
	}
}

/******************************************************
 * schaltet led nach bitmuster an
*******************************************************/
uint8_t show_image(uint8_t reps, uint8_t *reset)
{
    static uint32_t image_timer = 0;
    static uint8_t count = 0;
    static uint8_t image = 0;

    if(*reset)
    {
        count = 0;
        image = 0;
        image_timer = 0;
        *reset = 0;
    }

    if(HAL_GetTick() >= image_timer)
    {
        // Sind alle Bilder gezeigt?
        if(reps <= count)
        {
            return 1;
        }

        SSD1306_Fill(SSD1306_COLOR_BLACK);

        if(image == 0)
        {
            SSD1306_DrawBitmap(0, 0, image_1, 128, 64, SSD1306_COLOR_WHITE);
            image = 1;
        }
        else
        {
            SSD1306_DrawBitmap(0, 0, image_2, 128, 64, SSD1306_COLOR_WHITE);
            image = 0;
            count++;
        }

        SSD1306_UpdateScreen();

        image_timer = HAL_GetTick() + 3000;
    }

    return 0;
}
